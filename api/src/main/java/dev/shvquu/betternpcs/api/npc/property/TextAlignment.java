package dev.shvquu.betternpcs.api.npc.property;

/**
 * How the lines of a multi-line floating text are aligned relative to each other.
 *
 * @since 1.0.0
 */
public enum TextAlignment {

    /** Lines are centred on the NPC. */
    CENTER,

    /** Lines share a left edge. */
    LEFT,

    /** Lines share a right edge. */
    RIGHT
}
